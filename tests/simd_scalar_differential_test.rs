//! End-to-end SIMD/scalar differential coverage over generated, conformant VP9 streams.
//!
//! `simd::avx2_enabled()` caches both the CPU feature probe and `VP9DEC_NO_SIMD` in a
//! `OnceLock`, so changing the environment inside one test process cannot reliably select
//! both implementations. The parent test therefore starts this integration-test binary twice:
//! once with `VP9DEC_NO_SIMD` removed and once with it set. Each child verifies the selected
//! dispatch mode before decoding the same deterministic scenarios.
//!
//! Generation is syntax-aware, not byte mutation:
//!
//! - profile/bit-depth/subsampling values come from an explicitly valid table;
//! - modes, segmentation levels, loop-filter levels, and probabilities are selected only
//!   from their legal ranges;
//! - every coded block is lossless and skipped, so no coefficient token is present (and the
//!   malformed-coefficient SIMD/scalar wrap caveat cannot apply);
//! - the generated scaled-reference case uses the spec §8.5.2.3 maximum conformant ratio,
//!   exactly 2x, never a malformed ratio.
//!
//! The report contains both the generated bytes and every decoded output sample. Comparing the
//! reports byte-for-byte therefore checks the inputs were identical as well as the outputs.

mod common;

